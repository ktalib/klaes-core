{{--
  OP → File Property ID Matching.

  Left: the confirmed FILE, which is the control record. Its Property ID is the target
  and never moves. Right: the Occupancy Permits, searched by serial number because that
  is what is printed on the permit the officer is holding. Tick the ones that belong to
  the file, add them to the batch (repeating for as many serials as the file needs),
  then press Batch Match and every permit in the batch is moved onto the file's
  Property ID.

  The shell is the one match_op.blade.php uses and for the same two reasons:
  admin.header loads Tailwind v3 (layouts/app only carries v2, which has no arbitrary
  values and none of the slate/violet palette used here), and the
  "flex-1 overflow-auto relative" wrapper is what app-layout.css sizes the content pane
  with — without it the page renders in a half-width column beside the sidebar.

  Everything below is drawn and driven by public/js/op-propid-match.js, which keys off
  the ids on #op-propid-match and reads its endpoints from that element's data
  attributes. No markup here is generated by the script except the three result lists.
--}}

