    /**
     * Generate a new report
     */
    public function generate(Request $request)
    {
        // Check authorization
        if (!Auth::user()->can('generate-reports') && Auth::user()->type !== 'super admin') {
            return back()->with('error', 'You do not have permission to generate reports');
        }

        try {
            // Validate input
            $validated = $request->validate([
                'date_from' => 'required|date',
                'date_to' => 'required|date|after:date_from',
                'format' => 'required|in:csv,pdf,excel',
                'status' => 'nullable|in:ACTIVE,IDLE,INACTIVE',
                'user_search' => 'nullable|string',
            ]);

            // Prepare filters
            $filters = [
                'date_from' => $validated['date_from'],
                'date_to' => $validated['date_to'],
            ];

            if (!empty($validated['status'])) {
                $filters['status'] = $validated['status'];
            }

            // Generate report
            $result = $this->reportService->generateReport(
                $validated['format'],
                $filters,
                ['include_charts' => true]
            );

            if (!$result['success']) {
                return back()->with('error', $result['message'] ?? 'Failed to generate report');
            }

            // Log report generation
            Log::info("Report generated by {$request->user()->name}", [
                'format' => $validated['format'],
                'filename' => $result['filename'],
                'filters' => $filters,
            ]);

            // Return download or show success
            if ($request->has('download')) {
                return response()->download(
                    $result['path'],
                    $result['filename'],
                    ['Content-Type' => $this->getMimeType($result['format'])]
                );
            }

            return back()->with('success', "Report generated successfully: {$result['filename']} ({$result['size']} bytes)");

        } catch (\Illuminate\Validation\ValidationException $e) {
            return back()->withErrors($e->errors())->withInput();
        } catch (\Exception $e) {
            Log::error("Error generating report: {$e->getMessage()}");
            return back()->with('error', $e->getMessage());
        }
    }

