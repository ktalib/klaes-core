    /**
     * Schedule recurring report
     */
    public function scheduleReport(Request $request)
    {
        // Check authorization
        if (!Auth::user()->can('schedule-reports') && Auth::user()->type !== 'super admin') {
            return response()->json([
                'success' => false,
                'message' => 'Unauthorized',
            ], 403);
        }

        try {
            // Validate input
            $validated = $request->validate([
                'frequency' => 'required|in:daily,weekly,biweekly,monthly',
                'format' => 'required|in:csv,pdf,excel',
                'recipients' => 'required|email',
                'date_from' => 'nullable|date',
                'date_to' => 'nullable|date',
            ]);

            // Schedule report
            $result = $this->reportService->scheduleReport([
                'user_id' => Auth::id(),
                'frequency' => $validated['frequency'],
                'format' => $validated['format'],
                'recipients' => $validated['recipients'],
                'date_range' => [
                    'from' => $validated['date_from'] ?? null,
                    'to' => $validated['date_to'] ?? null,
                ],
            ]);

            Log::info("Report scheduled by {$request->user()->name}", [
                'frequency' => $validated['frequency'],
                'format' => $validated['format'],
            ]);

            return response()->json($result);

        } catch (\Illuminate\Validation\ValidationException $e) {
            return response()->json([
                'success' => false,
                'message' => 'Validation error',
                'errors' => $e->errors(),
            ], 422);
        } catch (\Exception $e) {
            Log::error("Error scheduling report: {$e->getMessage()}");
            return response()->json([
                'success' => false,
                'message' => $e->getMessage(),
            ], 500);
        }
    }

